void bvp_tableau(int method, tableau *t) {
    memset(t, 0, sizeof(*t));
    double r7 = sqrt(7.0), r21 = sqrt(21.0), r3 = sqrt(3.0);
    if (method == 2) {
        t->s = 2;
        t->c[1] = t->v[1] = 1;
        t->b[0] = t->b[1] = 0.5;
        t->defect[0] = 0.25;
        t->defect[1] = 0.75;
        return;
    }
    if (method == 4) {
        t->s = 3;
        t->extra = 1;
        t->c[0] = 0.0;
        t->c[1] = 1.0;
        t->c[2] = 0.5;
        t->v[0] = 0.0;
        t->v[1] = 1.0;
        t->v[2] = 0.5;
        t->b[0] = 1.0 / 6.0;
        t->b[1] = 1.0 / 6.0;
        t->b[2] = 2.0 / 3.0;
        t->x[2][0] = 1.0 / 8.0;
        t->x[2][1] = -1.0 / 8.0;
        t->x[2][2] = 0.0;
        t->ce[0] = 2.0 / 5.0;
        t->ve[0] = 2.0 / 5.0;
        t->xe[0][0] = 17.0 / 125.0;
        t->xe[0][1] = -13.0 / 125.0;
        t->xe[0][2] = -4.0 / 125.0;
        t->xe[0][3] = 0.0;
        t->defect[0] = 0.226;
        t->defect[1] = 1.0 - 0.226;
        return;
    }
    if (method == 6) {
        t->s = 5;
        t->extra = 3;
        t->c[0] = 0.0;
        t->c[1] = 1.0;
        t->c[2] = 0.5 - r21 / 14.0;
        t->c[3] = 0.5 + r21 / 14.0;
        t->c[4] = 0.5;
        t->v[0] = 0.0;
        t->v[1] = 1.0;
        t->v[2] = 0.5 - 9.0 * r21 / 98.0;
        t->v[3] = 0.5 + 9.0 * r21 / 98.0;
        t->v[4] = 0.5;
        t->b[0] = 1.0 / 20.0;
        t->b[1] = 1.0 / 20.0;
        t->b[2] = 49.0 / 180.0;
        t->b[3] = 49.0 / 180.0;
        t->b[4] = 16.0 / 45.0;
        t->x[2][0] = 1.0 / 14.0 + r21 / 98.0;
        t->x[2][1] = -1.0 / 14.0 + r21 / 98.0;
        t->x[2][2] = 0.0;
        t->x[2][3] = 0.0;
        t->x[2][4] = 0.0;
        t->x[3][0] = 1.0 / 14.0 - r21 / 98.0;
        t->x[3][1] = -1.0 / 14.0 - r21 / 98.0;
        t->x[3][2] = 0.0;
        t->x[3][3] = 0.0;
        t->x[3][4] = 0.0;
        t->x[4][0] = -5.0 / 128.0;
        t->x[4][1] = 5.0 / 128.0;
        t->x[4][2] = 7.0 * r21 / 128.0;
        t->x[4][3] = -7.0 * r21 / 128.0;
        t->x[4][4] = 0.0;
        t->ce[0] = 0.5;
        t->ce[1] = 0.5 - r7 / 14.0;
        t->ce[2] = 87.0 / 100.0;
        t->ve[0] = 0.5;
        t->ve[1] = 0.5 - r7 / 14.0;
        t->ve[2] = 87.0 / 100.0;
        t->xe[0][0] = 1.0 / 64.0;
        t->xe[0][1] = -1.0 / 64.0;
        t->xe[0][2] = (7.0 / 192.0) * r21;
        t->xe[0][3] = -(7.0 / 192.0) * r21;
        t->xe[0][4] = 0.0;
        t->xe[0][5] = 0.0;
        t->xe[0][6] = 0.0;
        t->xe[0][7] = 0.0;
        t->xe[1][0] = 3.0 / 112.0 + (9.0 / 1960.0) * r7;
        t->xe[1][1] = -3.0 / 112.0 + (9.0 / 1960.0) * r7;
        t->xe[1][2] = (11.0 / 840.0) * r7 + (3.0 / 112.0) * r7 * r3;
        t->xe[1][3] = (11.0 / 840.0) * r7 - (3.0 / 112.0) * r7 * r3;
        t->xe[1][4] = (88.0 / 5145.0) * r7;
        t->xe[1][5] = (-18.0 / 343.0) * r7;
        t->xe[1][6] = 0.0;
        t->xe[1][7] = 0.0;
        t->xe[2][0] = 2707592511.0 / 1000000000000.0 - (1006699707.0 / 1000000000000.0) * r7;
        t->xe[2][1] = -51527976591.0 / 1000000000000.0 - (1006699707.0 / 1000000000000.0) * r7;
        t->xe[2][2] = -610366393.0 / 75000000000.0 + (7046897949.0 / 1000000000000.0) * r7 +
                      (14508670449.0 / 1000000000000.0) * r7 * r3;
        t->xe[2][3] = -610366393.0 / 75000000000.0 + (7046897949.0 / 1000000000000.0) * r7 -
                      (14508670449.0 / 1000000000000.0) * r7 * r3;
        t->xe[2][4] = -12456457.0 / 1171875000.0 + (1006699707.0 / 109375000000.0) * r7;
        t->xe[2][5] = (3020099121.0 / 437500000000.0) * r7 + 47328957.0 / 625000000.0;
        t->xe[2][6] = (-7046897949.0 / 250000000000.0) * r7;
        t->xe[2][7] = 0.0;
        t->defect[0] = 0.4;
        t->defect[1] = 0.6;
        return;
    }
    t->s = 9;
    double r = sqrt(21.0);
    t->x[2][0] = 9.0 / 64.0;
    t->x[2][1] = -3.0 / 64.0;
    t->x[3][0] = 3.0 / 64.0;
    t->x[3][1] = -9.0 / 64.0;
    t->x[4][0] = 757.0 / 9216.0;
    t->x[4][1] = 43.0 / 9216.0;
    t->x[4][2] = 235.0 / 4608.0;
    t->x[4][3] = -59.0 / 4608.0;
    t->x[5][0] = -43.0 / 9216.0;
    t->x[5][1] = -757.0 / 9216.0;
    t->x[5][2] = 59.0 / 4608.0;
    t->x[5][3] = -235.0 / 4608.0;
    t->x[6][0] = 3451.0 / 139258.0 + 717.0 * r / 139258.0;
    t->x[6][1] = -3451.0 / 139258.0 + 717.0 * r / 139258.0;
    t->x[7][0] = 3451.0 / 139258.0 - 717.0 * r / 139258.0;
    t->x[7][1] = -3451.0 / 139258.0 - 717.0 * r / 139258.0;
    t->x[6][4] = 64.0 / 1029.0 + 1024.0 * r / 69629.0;
    t->x[7][4] = 64.0 / 1029.0 - 1024.0 * r / 69629.0;
    t->x[6][5] = -64.0 / 1029.0 + 1024.0 * r / 69629.0;
    t->x[7][5] = -64.0 / 1029.0 - 1024.0 * r / 69629.0;
    t->x[8][0] = 29.0 / 896.0;
    t->x[8][1] = -29.0 / 896.0;
    t->x[8][4] = -2.0 / 21.0;
    t->x[8][5] = 2.0 / 21.0;
    t->x[8][6] = 7.0 * r / 128.0;
    t->x[8][7] = -7.0 * r / 128.0;
    t->c[0] = 0.0;
    t->c[1] = 1.0;
    t->c[2] = 0.25;
    t->c[3] = 0.75;
    t->c[4] = 0.125;
    t->c[5] = 0.875;
    t->c[6] = 0.5 - r / 14.0;
    t->c[7] = 0.5 + r / 14.0;
    t->c[8] = 0.5;
    t->v[0] = 0.0;
    t->v[1] = 1.0;
    t->v[2] = 5.0 / 32.0;
    t->v[3] = 27.0 / 32.0;
    t->v[4] = 0.0;
    t->v[5] = 1.0;
    t->v[6] = 0.5 - 2211.0 * r / 19894.0;
    t->v[7] = 0.5 + 2211.0 * r / 19894.0;
    t->v[8] = 0.5;
    t->b[0] = 1.0 / 20.0;
    t->b[1] = 1.0 / 20.0;
    t->b[2] = 0.0;
    t->b[3] = 0.0;
    t->b[4] = 0.0;
    t->b[5] = 0.0;
    t->b[6] = 49.0 / 180.0;
    t->b[7] = 49.0 / 180.0;
    t->b[8] = 16.0 / 45.0;
}
size_t bvp_weights(bvp_method method, double tau, double w[8], double wp[8]) {
    double t = tau;
    memset(w, 0, 8 * sizeof(double));
    memset(wp, 0, 8 * sizeof(double));
    if (method == BVP_MIRK2) {

        {

            w[0] = t * (1.0 - t / 2.0);
            w[1] = t * t / 2.0;
            w[2] = 0.0;
            w[3] = 0.0;
            w[4] = 0.0;
            w[5] = 0.0;
            w[6] = 0.0;
            w[7] = 0.0;
        }
        {

            wp[0] = 1.0 - t;
            wp[1] = t;
            wp[2] = 0.0;
            wp[3] = 0.0;
            wp[4] = 0.0;
            wp[5] = 0.0;
            wp[6] = 0.0;
            wp[7] = 0.0;
        }
        return 2;
    }
    if (method == BVP_MIRK4) {

        {
            double t2 = t * t;

            w[0] = -t * (3.0 * t - 4.0) * (5.0 * t2 - 6.0 * t + 3.0) / 12.0;
            w[1] = t2 * (5.0 * t2 - 6.0 * t + 2.0) / 6.0;
            w[2] = -2.0 / 3.0 * t2 * (3.0 * t - 2.0) * (5.0 * t - 6.0);
            w[3] = 125.0 / 12.0 * t2 * ((t - 1.0) * (t - 1.0));
            w[4] = 0.0;
            w[5] = 0.0;
            w[6] = 0.0;
            w[7] = 0.0;
        }
        {

            wp[0] = -(t - 1.0) * (5.0 * t - 2.0) * (2.0 * t - 1.0) / 2.0;
            wp[1] = t * (5.0 * t - 2.0) * (2.0 * t - 1.0) / 3.0;
            wp[2] = -8.0 * t * (t - 1.0) * (5.0 * t - 2.0);
            wp[3] = 125.0 / 6.0 * t * (t - 1.0) * (2.0 * t - 1.0);
            wp[4] = 0.0;
            wp[5] = 0.0;
            wp[6] = 0.0;
            wp[7] = 0.0;
        }
        return 4;
    }
    if (method == BVP_MIRK6) {

        double r = sqrt(7.0);

        {
            double t2 = t * t;
            double t3 = t2 * t;

            double t4 = t2 * t2;
            double t5 = t4 * t;
            double tm1_squared = ((t - 1.0) * (t - 1.0));
            double common_polynomial = 14000.0 * t4 - 48216.0 * t3 + 1200.0 * r * t3 -
                                       3555.0 * r * t2 + 62790.0 * t2 + 3610.0 * r * t -
                                       37450.0 * t + 9135.0 - 1305.0 * r;

            w[0] = -(12233.0 + 1450.0 * r) *
                   (800086000.0 * t5 + 63579600.0 * r * t4 - 2936650584.0 * t4 + 4235152620.0 * t3 -
                    201404565.0 * r * t3 + 232506630.0 * r * t2 - 3033109390.0 * t2 +
                    1116511695.0 * t - 116253315.0 * r * t + 22707000.0 * r - 191568780.0) *
                   t / 2112984835740.0;
            w[1] = -(-10799.0 + 650.0 * r) *
                   (24962000.0 * t4 + 473200.0 * r * t3 - 67024328.0 * t3 - 751855.0 * r * t2 +
                    66629600.0 * t2 - 29507250.0 * t + 236210.0 * r * t + 5080365.0 + 50895.0 * r) *
                   t2 / 29551834260.0;
            w[2] = 7.0 / 1274940.0 * (259.0 + 50.0 * r) * common_polynomial * t2;
            w[3] = 7.0 / 1274940.0 * (259.0 + 50.0 * r) * common_polynomial * t2;
            w[4] = 16.0 / 2231145.0 * (259.0 + 50.0 * r) * common_polynomial * t2;
            w[5] = 4.0 / 1227278493.0 * (740.0 * r - 6083.0) *
                   (1561000.0 * t2 - 2461284.0 * t - 109520.0 * r * t + 979272.0 + 86913.0 * r) *
                   tm1_squared * t2;
            w[6] = -49.0 / 63747.0 * r * (20000.0 * t2 - 20000.0 * t + 3393.0) * tm1_squared * t2;
            w[7] = -1250000000.0 / 889206903.0 * (28.0 * t2 - 28.0 * t + 9.0) * tm1_squared * t2;
        }
        {

            wp[0] = (1450.0 * r + 12233.0) * (14.0 * t - 7.0 + r) * (t - 1.0) *
                    (-400043.0 * t + 75481.0 + 2083.0 * r) * (100.0 * t - 87.0) * (2.0 * t - 1.0) /
                    493029795006.0;
            wp[1] = -(650.0 * r - 10799.0) * (14.0 * t - 7.0 + r) *
                    (37443.0 * t - 13762.0 - 2083.0 * r) * (100.0 * t - 87.0) * (2.0 * t - 1.0) *
                    t / 20686283982.0;
            wp[2] = 7.0 / 42498.0 * (259.0 + 50.0 * r) * (14.0 * t - 7.0 + r) * (t - 1.0) *
                    (100.0 * t - 87.0) * (2.0 * t - 1.0) * t;
            wp[3] = 7.0 / 42498.0 * (259.0 + 50.0 * r) * (14.0 * t - 7.0 + r) * (t - 1.0) *
                    (100.0 * t - 87.0) * (2.0 * t - 1.0) * t;
            wp[4] = 32.0 / 148743.0 * (259.0 + 50.0 * r) * (14.0 * t - 7.0 + r) * (t - 1.0) *
                    (100.0 * t - 87.0) * (2.0 * t - 1.0) * t;
            wp[5] = 4.0 / 1227278493.0 * (740.0 * r - 6083.0) * (14.0 * t - 7.0 + r) * (t - 1.0) *
                    (100.0 * t - 87.0) * (6690.0 * t - 4085.0 - 869.0 * r) * t;
            wp[6] = -98.0 / 21249.0 * r * (t - 1.0) * (100.0 * t - 13.0) * (100.0 * t - 87.0) *
                    (2.0 * t - 1.0) * t;
            wp[7] = -1250000000.0 / 2074816107.0 * (14.0 * t - 7.0 + r) * (t - 1.0) *
                    (14.0 * t - 7.0 - r) * (2.0 * t - 1.0) * t;
        }
        return 8;
    }
    return 0;
}
